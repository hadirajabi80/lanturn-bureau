/**
 * `npm run icons` — collects every lucide icon name referenced by content (clue.icon,
 * scene.props[]) plus a small UI set, and emits src/components/ui/iconRegistry.ts with explicit
 * named imports so the bundle only ships those icons (instead of lucide's full ~1.5 MB map).
 */
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as Lucide from 'lucide-react';
import { CASES } from '../src/data/index.ts';
import { BUREAU } from '../src/data/bureau.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'src/components/ui/iconRegistry.ts');

/** Icons referenced by name from UI code (KIND_META, fallbacks, common UI glyphs). */
const UI_ICONS = [
  // fallbacks
  'FileQuestion', 'Sparkles',
  // KIND_META in ClueIcon.tsx
  'Package', 'FileText', 'MessageSquareQuote', 'Cpu', 'Camera', 'Microscope',
  // common investigation glyphs
  'Lock', 'Search', 'Fingerprint', 'MapPin', 'Clock', 'Scale', 'Key', 'KeyRound', 'Eye',
];

const REGISTRY = Lucide as unknown as Record<string, unknown>;
const NOT_ICONS = new Set(['createLucideIcon', 'icons', 'default', 'Icon', 'LucideIcon']);

const isComponent = (v: unknown): boolean =>
  typeof v === 'function' || (typeof v === 'object' && v !== null && '$$typeof' in v && 'render' in v);

const pascal = (s: string): string =>
  s
    .trim()
    .replace(/[-_\s]+(.)?/g, (_, c: string | undefined) => (c ? c.toUpperCase() : ''))
    .replace(/^(.)/, (c) => c.toUpperCase());

/** Map a content name to a real lucide export name (or null if unknown). */
function canonical(name: string): string | null {
  const p = pascal(name);
  const stripped = p.endsWith('Icon') && p.length > 4 ? p.slice(0, -4) : p;
  for (const c of [name.trim(), p, stripped, `${p}Icon`]) {
    if (!c || NOT_ICONS.has(c) || c.startsWith('Lucide')) continue;
    if (isComponent(REGISTRY[c])) return c;
  }
  return null;
}

const wanted = new Map<string, string>(); // raw name -> where
const add = (name: unknown, where: string) => {
  if (typeof name === 'string' && name.trim() && !wanted.has(name)) wanted.set(name, where);
};

for (const c of CASES) {
  for (const clue of c.clues) add(clue.icon, `${c.id} clue ${clue.id}`);
  for (const scene of c.scenes) for (const p of scene.props) add(p, `${c.id} scene ${scene.id}`);
}
// Characters don't carry icons today, but pick up any `icon` field if one is added later.
for (const ch of Object.values(BUREAU)) add((ch as unknown as { icon?: unknown }).icon, `bureau ${ch.id}`);
for (const n of UI_ICONS) add(n, 'ui');

const resolved = new Set<string>();
const missing: string[] = [];
for (const [raw, where] of wanted) {
  const name = canonical(raw);
  if (name) resolved.add(name);
  else missing.push(`  "${raw}" (${where})`);
}

const names = [...resolved].sort();
const src = `// AUTO-GENERATED by scripts/collect-icons.ts — do not edit. Run \`npm run icons\`.
import type { LucideIcon } from 'lucide-react';
import {
${names.map((n) => `  ${n},`).join('\n')}
} from 'lucide-react';

/** Every lucide icon that content or UI resolves by name. Keys are lucide export names. */
export const ICONS: Record<string, LucideIcon> = {
${names.map((n) => `  ${n},`).join('\n')}
};
`;

const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (prev !== src) writeFileSync(OUT, src);
console.log(`icons: ${names.length} icons -> ${OUT.replace(ROOT, '.')}${prev === src ? ' (unchanged)' : ''}`);
if (missing.length) console.warn(`icons: ${missing.length} unknown name(s) will fall back at runtime:\n${missing.join('\n')}`);
